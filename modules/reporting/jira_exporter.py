class MITRENavigatorExporter:
    """MITRE ATT&CK Navigator exporter."""

    def generate_layer(self, findings: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Generate ATT&CK Navigator layer JSON."""
        techniques = {}

        for finding in findings:
            mitre = finding.get("mitre", []) or finding.get("attack_mapping", {})
            if isinstance(mitre, dict):
                # From behavior analyzer
                for cat, techs in mitre.items():
                    for tech in techs:
                        # Extract technique ID like T1055
                        import re
                        match = re.search(r"T\d+(?:\.\d+)?", tech)
                        if match:
                            tid = match.group(0)
                            if tid not in techniques:
                                techniques[tid] = {"count": 0, "findings": []}
                            techniques[tid]["count"] += 1
                            techniques[tid]["findings"].append(finding.get("type",""))
            elif isinstance(mitre, list):
                for tech in mitre:
                    import re
                    match = re.search(r"T\d+(?:\.\d+)?", str(tech))
                    if match:
                        tid = match.group(0)
                        if tid not in techniques:
                            techniques[tid] = {"count": 0, "findings": []}
                        techniques[tid]["count"] += 1

        # Build layer
        layer = {
            "name": "r3con v7.0 - Threat Analysis",
            "versions": {"attack": "13", "navigator": "4.8.0", "layer": "4.4"},
            "domain": "enterprise-attack",
            "description": f"Generated from {len(findings)} findings",
            "techniques": [],
        }

        for tid, data in techniques.items():
            score = min(data["count"] * 20, 100)
            color = "#ff0000" if score >= 60 else "#ff8000" if score >= 30 else "#ffff00" if score >= 10 else "#ffffff"
            layer["techniques"].append({
                "techniqueID": tid,
                "score": score,
                "color": color,
                "comment": f"{data['count']} findings: {', '.join(data['findings'][:3])}",
                "enabled": True,
                "showSubtechniques": True,
            })

        return {
            "status": "ok",
            "engine": "mitre_navigator",
            "technique_count": len(techniques),
            "layer": layer,
        }
